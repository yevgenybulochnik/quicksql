"""Emit the Postgres stress seed (SQL) for the compose server's ``quicksql``
database, shaped like a large warehouse:

    uv run python stress/catalog/gen_pg_seed.py | psql …   # stack.py seed-pg does this

* ``stress_s000`` … — many schemas, each holding a few small tables;
* ``stress_many`` — one schema with thousands of date-sharded tables;
* ``stress_wide.wide_1500`` / ``wide_1590`` — 1500 commented columns, and
  close to Postgres's 1600-column limit.

The stress notebook connects as ``stress_reader``, whose password is distinctive
on purpose: a check that it never leaks into the catalog's output can't be
fooled by the same word appearing in a user or database name.

Deterministic and idempotent: every ``stress_*`` schema is dropped and rebuilt
with DO blocks rather than thousands of literal statements.
"""

from __future__ import annotations

import argparse
import sys

READER = "stress_reader"
READER_PASSWORD = "hunter2-stress-secret"


def sql(schemas: int, tables_per_schema: int, many: int, description_len: int) -> str:
    desc = ("lorem ipsum dolor sit amet " * (description_len // 27 + 1))[:description_len]
    return f"""\
-- generated by stress/catalog/gen_pg_seed.py: edit the generator, not this
-- Thousands of tables in one transaction run out of lock slots
-- (max_locks_per_transaction): every loop commits in batches.
DO $$
DECLARE t record; n int := 0;
BEGIN
  FOR t IN SELECT schemaname, tablename FROM pg_tables WHERE schemaname LIKE 'stress\\_%' LOOP
    EXECUTE format('DROP TABLE %I.%I', t.schemaname, t.tablename);
    n := n + 1;
    IF n % 500 = 0 THEN COMMIT; END IF;
  END LOOP;
  COMMIT;
END $$;
DO $$
DECLARE s text;
BEGIN
  FOR s IN SELECT nspname FROM pg_namespace WHERE nspname LIKE 'stress\\_%' LOOP
    EXECUTE format('DROP SCHEMA %I', s);
  END LOOP;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{READER}') THEN
    CREATE ROLE {READER} LOGIN;
  END IF;
END $$;
ALTER ROLE {READER} PASSWORD '{READER_PASSWORD}';

-- many schemas, a few small tables each
DO $$
BEGIN
  FOR i IN 0..{schemas - 1} LOOP
    EXECUTE format('CREATE SCHEMA %I', 'stress_s' || lpad(i::text, 3, '0'));
    FOR t IN 0..{tables_per_schema - 1} LOOP
      EXECUTE format(
        'CREATE TABLE %I.%I (id bigint NOT NULL, name text, amount numeric, created_at timestamptz)',
        'stress_s' || lpad(i::text, 3, '0'), 't_' || lpad(t::text, 2, '0'));
    END LOOP;
    IF i % 50 = 49 THEN COMMIT; END IF;
  END LOOP;
END $$;

-- one schema, thousands of date-sharded tables
CREATE SCHEMA stress_many;
DO $$
BEGIN
  FOR i IN 0..{many - 1} LOOP
    EXECUTE format('CREATE TABLE stress_many.%I (id bigint NOT NULL, payload text)',
                   'events_' || to_char(date '2024-01-01' + i, 'YYYYMMDD'));
    IF i % 500 = 499 THEN COMMIT; END IF;
  END LOOP;
END $$;

-- wide tables, commented columns
CREATE SCHEMA stress_wide;
DO $$
DECLARE cols text;
BEGIN
  SELECT string_agg(format('col_%s text', lpad(i::text, 4, '0')), ', ' ORDER BY i)
    INTO cols FROM generate_series(0, 1499) AS i;
  EXECUTE 'CREATE TABLE stress_wide.wide_1500 (' || cols || ')';
  FOR i IN 0..1499 LOOP
    EXECUTE format('COMMENT ON COLUMN stress_wide.wide_1500.%I IS %L',
                   'col_' || lpad(i::text, 4, '0'), '{desc}');
  END LOOP;
  SELECT string_agg(format('c_%s int', lpad(i::text, 4, '0')), ', ' ORDER BY i)
    INTO cols FROM generate_series(0, 1589) AS i;
  EXECUTE 'CREATE TABLE stress_wide.wide_1590 (' || cols || ')';
END $$;

-- the reader sees every stress schema
DO $$
DECLARE s text;
BEGIN
  FOR s IN SELECT nspname FROM pg_namespace WHERE nspname LIKE 'stress\\_%' LOOP
    EXECUTE format('GRANT USAGE ON SCHEMA %I TO {READER}', s);
    EXECUTE format('GRANT SELECT ON ALL TABLES IN SCHEMA %I TO {READER}', s);
    COMMIT;
  END LOOP;
END $$;
"""


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--schemas", type=int, default=300)
    ap.add_argument("--tables-per-schema", type=int, default=5)
    ap.add_argument("--many", type=int, default=3000)
    ap.add_argument("--description-len", type=int, default=200)
    args = ap.parse_args(argv)
    sys.stdout.write(sql(args.schemas, args.tables_per_schema, args.many, args.description_len))


if __name__ == "__main__":
    main()
