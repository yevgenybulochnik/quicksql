"""A notebook's vocabulary, read from its registries: the directives it can
write (key, scope, type, default, merge, whether editing one reruns the cell,
the plugin that owns it, what it does) and the engines and sinks they name.

``quicksql directives`` prints it for a notebook, its ``quicksqlrc.py`` and
``--plugins`` included. The packaged skill's ``references/directives.md`` is
the builtins' vocabulary rendered by ``directives_markdown``, and a test keeps
the committed file equal to it.
"""

from __future__ import annotations

import sys
import types
import typing
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import yaml

from .registry import Registries


@dataclass(frozen=True)
class Directive:
    key: str
    scope: str  # global | cell | both
    type: str
    default: Any
    merge: str  # override | deep | extend
    reruns: bool  # editing it changes the cell's fingerprint: a save reruns it
    plugin: str
    source: str  # "builtin", or the file that defines the plugin (e.g. quicksqlrc.py)
    description: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def directives(registries: Registries) -> list[Directive]:
    """Every directive the registries' plugins declare, by key."""
    rows = []
    for key, entry in registries.plugins.field_map().items():
        info = entry.info
        extra = info.json_schema_extra if isinstance(info.json_schema_extra, dict) else {}
        plugin = type(entry.plugin)
        rows.append(
            Directive(
                key=key,
                scope=entry.plugin.scope.value,
                type=_type_name(info.annotation),
                default=info.get_default(call_default_factory=True),
                merge=str(extra.get("qsql_merge", "override")),
                reruns=bool(extra.get("qsql_affects_results", True)),
                plugin=entry.plugin.name,
                source=_source(plugin),
                description=info.description or _first_line(plugin.__doc__),
            )
        )
    return sorted(rows, key=lambda d: d.key)


def engines(registries: Registries) -> list[dict[str, Any]]:
    """The engines ``engine:`` (or ``input``'s key) can name."""
    out = []
    for name in registries.executors.names():
        executor = registries.executors.get(name)
        out.append({
            "name": name,
            "dialect": executor.dialect,
            "input_shorthand": executor.input_shorthand,
            "source": _source(type(executor)),
            "description": _doc(type(executor)),
        })
    return out


def sinks(registries: Registries) -> list[dict[str, Any]]:
    """The sinks ``output.type`` can name."""
    out = []
    for name in registries.sinks.names():
        sink = registries.sinks.get(name)
        out.append({
            "name": name,
            "lands_output": bool(sink.lands_output),
            "source": _source(sink),
            "description": _doc(sink),
        })
    return out


def directives_markdown(registries: Registries) -> str:
    """The vocabulary as a Markdown reference (the skill's directives.md)."""
    lines = [
        "# Directives",
        "",
        "Generated by `quicksql directives --markdown` from quicksql's builtins. A notebook",
        "with plugins of its own (a `quicksqlrc.py` next to it, or `--plugins`) can write more:",
        "`quicksql directives NOTEBOOK` lists exactly what that notebook can write.",
        "",
        "Write a directive as a comment: `-- @key: value` on one line, or YAML in a",
        "`/*@ ... */` block. Values are literal YAML; only the SQL body is Jinja.",
        "",
        "- **Scope**: `global` goes in the header (before the first `@cell`), `cell` in a cell,",
        "  `both` in either; a cell's value applies over the header's.",
        "- **Merge**: how a cell's value combines with the header's and with `--set`",
        "  overrides: `override` replaces it, `deep` merges mappings key by key, `extend`",
        "  appends to the list.",
        "- **Reruns**: whether editing it changes the cell's fingerprint, so a save reruns the",
        "  cell and `status` calls its output stale.",
        "",
        "| Directive | Scope | Type | Default | Merge | Reruns | What it does |",
        "|---|---|---|---|---|---|---|",
    ]
    for d in directives(registries):
        lines.append(
            f"| `{d.key}` | {d.scope} | {d.type} | `{yaml_flow(d.default)}` | {d.merge} | "
            f"{'yes' if d.reruns else 'no'} | {_cell(d.description)} |"
        )
    lines += [
        "",
        "## Engines `engine:` can name",
        "",
        "| Engine | SQL dialect | `input` shorthand |",
        "|---|---|---|",
    ]
    for e in engines(registries):
        lines.append(
            f"| `{e['name']}` | {e['dialect'] or 'generic'} | "
            f"`{{{e['name']}: <{e['input_shorthand']}>}}` |"
        )
    lines += [
        "",
        "## Sinks `output.type` can name",
        "",
        "| Sink | Lands an output | What it is |",
        "|---|---|---|",
    ]
    for s in sinks(registries):
        lines.append(
            f"| `{s['name']}` | {'yes' if s['lands_output'] else 'no'} | {_cell(s['description'])} |"
        )
    return "\n".join(lines) + "\n"


def _type_name(annotation: Any) -> str:
    origin, args = typing.get_origin(annotation), typing.get_args(annotation)
    if origin in (typing.Union, types.UnionType):
        rest = [a for a in args if a is not type(None)]
        name = " or ".join(_type_name(a) for a in rest)
        return f"{name} or null" if len(rest) < len(args) else name
    if annotation is bool:
        return "boolean"
    if annotation is str:
        return "string"
    if annotation is int:
        return "integer"
    if annotation is float:
        return "number"
    if annotation is dict or origin is dict:
        return "mapping"
    if annotation is list or origin is list:
        return f"list of {_type_name(args[0])}s" if args else "list"
    if annotation is Any:
        return "any"
    return getattr(annotation, "__name__", str(annotation))


def _source(cls: type) -> str:
    module = cls.__module__
    if module == "quicksql" or module.startswith("quicksql."):
        return "builtin"
    path = getattr(sys.modules.get(module), "__file__", None)
    return Path(path).name if path else module


def _doc(cls: type) -> str:
    """A class's first doc line, else its module's."""
    return _first_line(cls.__doc__) or _first_line(getattr(sys.modules.get(cls.__module__), "__doc__", None))


def _first_line(doc: str | None) -> str:
    return (doc or "").strip().split("\n\n")[0].replace("\n", " ").strip()


def yaml_flow(value: Any) -> str:
    """A value as one line of YAML (``{type: parquet, dir: data/}``)."""
    text = yaml.safe_dump(value, default_flow_style=True, sort_keys=False).strip()
    return text.removesuffix("...").strip()


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")
